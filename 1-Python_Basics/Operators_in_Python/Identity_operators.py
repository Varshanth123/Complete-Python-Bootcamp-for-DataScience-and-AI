# Identity Operators 

'''
is (Identity): Returns True if both operands are the "same" object.
is not (Non-Identity): Returns True if both operands are "not the same" object.
'''

list1=[1,3,4,2]
list2=[1,2,3,4]

print("is both the lists are same ? ",list1 is list2)
print("is both the lista are not same ? ",list1 is not list2)