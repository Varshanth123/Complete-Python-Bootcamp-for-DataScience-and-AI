# Assignment operator 
a=int(input("Enter A value "))
b=int(input("Enter B value "))

a=b
print("A=B : A=",a)

a+=b
print("A=A+B : A=",a)

a-=b
print("A=A-B : A=",a)

a*=b
print("A=A*B : A=",a)

a//=b
print("A=A//B : A=",a)

a**=b
print("A=A^B : A=",a)

a/=b
print("A=A/B : A=",a)

a%=b
print("A=A%B : A=",a)