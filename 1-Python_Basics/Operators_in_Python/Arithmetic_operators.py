a=int(input("Enter A value : "))
b=int(input("Enter B value : "))

#Addition
print("A+b = ",a+b)

#Subtraction
print("A-B = ",a-b)

#Multiplication
print("A*B = ",a*b)

#Division
print("A/B = ",a/b)

#Floor Division (it gives the quotient without the decimal part)
print("A//B = ",a//b)

#Reminder
print("A%B = ",a%b)

#power
print("A power B = ",a**b)