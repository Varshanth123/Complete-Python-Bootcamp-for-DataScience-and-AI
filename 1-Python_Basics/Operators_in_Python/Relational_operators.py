# Relational operator
a=int(input("Enter A value "))
b=int(input("Enter B value "))

# > greater than 
print("Is A is greater than B? ",a>b)

# >= greater than or equal to 
print("Is A is greater than or equal to B? ",a>=b)

#<=lesser then or equal to 
print("Is A is lesser than or equal to B? ",a<=b)

# == equal or not
print("Is A is equal to B? ",a==b)

# != is not equal to or not 
print("IS A is notequal to B? ",a!=b)